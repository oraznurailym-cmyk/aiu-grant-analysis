    tq = pd.DataFrame({"Квота": list(qa.keys())})
    for i, y in enumerate(Y):
        tq[f"AIU {y}"] = [qa[q][i] for q in qa]
    for i, y in enumerate(Y):
        tq[f"AIU үлесі {y}, %"] = [round(_pct(qa[q][i], aiu[i]), 1) for q in qa]
    st.dataframe(tq, hide_index=True, **_stretch())

